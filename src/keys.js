// ============================================================================
//  keys.js —— 记住「现在哪些键是按住的」
//
//  这个模块不碰浏览器：它不知道什么叫 keydown、什么叫 blur、什么叫鼠标点击。
//  它只是被通知「有人按下了 w」「全部清空」。
//
//  这样拆的好处：它能被自动化测试（见 keys.test.js）。
//  「监听浏览器事件」那部分留在 main.js，那部分测不了，但很小。
// ============================================================================

export function createKeyState() {
  // Set = 不重复的集合。同一个键按两次只会存一份，正好符合"按住"的语义。
  const held = new Set();

  return {
    /** 某个键被按下了 */
    press(key) {
      held.add(key);
    },

    /** 某个键被松开了 */
    release(key) {
      held.delete(key);
    },

    /**
     * 清空所有按键。
     *
     * 什么时候用：窗口失去焦点时（用户去点别的窗口了）。
     * 为什么必须用：按下 w 之后切走，那个「松开 w」的事件会发生在**别的窗口**里，
     * 永远不会送到这个页面。不主动清空的话，游戏会一直以为 w 还按着——
     * 车就一直往前冲。
     */
    clearAll() {
      held.clear();
    },

    /** 这个键现在按着吗 */
    isHeld(key) {
      return held.has(key);
    },
  };
}
